// 漢字1文字ごとの読み。読みの候補を総当たりで作るために使う。
//
// なぜ持つか：形態素解析器は、辞書に無い複合語を分解して読むと外す
// （食洗機 → 食/洗/機 → ショクアライキ）。家電売場の言葉は辞書に
// 載っていないものが多く、一般の辞書を新しくしても埋まらない。
//
// そこで「当てる」のをやめて、**組合せを並べて人に選んでもらう**。
// 選ぶのが人なら、1位が当たっている必要はなく、候補に入っていればよい。
// 総当たりは、正しい読みをほぼ必ず含む（漢字の標準的な読みの組合せだから）。
//
// on  … 音読み（漢語。複合語では音どうしで揃うのが普通）
// kun … 訓読み（和語。送り仮名が付くのはこちら）
// どちらも「よく使う順」に並べる。並び順は候補の順位付けに使う。
//
// 載っていない漢字は候補を作れない。そのときは候補を出さず、入力欄だけ出す。

