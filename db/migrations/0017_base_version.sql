-- 修正案が「どの本文を直したものか」を覚える。
--
-- これが無いと、同じナレッジに2人が同時に修正案を出したとき、**片方が黙って消える**。
--   A が公開中の v1 を直して v2（承認待ち）
--   B も公開中の v1 を直して v3（承認待ち）… B の案に A の修正は入っていない
--   承認者が v3 を通すと、publish() が「自分より古い承認待ち」を閉じるので A の修正は消える
--   逆の順に通すと、今度は v3 が A の修正を上書きする
-- どちらの順でも、A は何も知らされない。
--
-- base_version を見れば「この案は、いまの本文より前のものを直したものだ」と分かるので、
-- 承認の時点で止められる（knowledge.ts の approveVersion）。
--
-- 既存の行と、最初の版（v1）は NULL。NULL は「土台が分からない／土台が無い」の意味で、
-- その場合は止めない（前からあるデータを承認できなくすると、運用が止まる）。

BEGIN;

ALTER TABLE knowledge_versions ADD COLUMN base_version integer;

COMMIT;
